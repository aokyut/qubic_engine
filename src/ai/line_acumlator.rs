// ハッシュ管理
// Late Move Reduction
pub fn negscout_hash_lineinfo(
    (att, def): UBoard, 
    line_info: &LineInfo, 
    is_black: bool, 
    depth: usize, 
    max_depth: usize,
    alpha: f32,
    beta: f32,
    hashmap: &mut HashMap<u128, (Fail, usize)>,
    e: &Box<dyn LineInfoEvaluator>
) -> (Vec<Action>, Fail){
    use Fail::*;

    let four_mask = get_reach_mask(att, def);
    if four_mask != 0 {
        let action = four_mask & (!four_mask + 1);
        return (vec![action], Ex(1.0))
    }
    let stone = att | def;
    // あと一箇所しか置ける場所がなければ引き分けが確定している。
    if stone.count_ones() == 63 {
        return (vec![!stone], Ex(0.0));
    }

    let mut max_val = -2.0;
    let mut max_action = Vec::new();
    let mut alpha = alpha;

    if depth <= 1{
        for (action, idx) in LSBGenerator::from_uboard((att, def)){
            let next_line_info = line_info.next(idx);
            let val = -e.evaluate(&(def, att), &next_line_info);
            if val > max_val{
                max_val = val;
                max_action = vec![action];
                if max_val > alpha {
                    alpha = max_val;
                    if alpha >= beta{
                        return (max_action, High(max_val))
                    }
                }
            }else if val == max_val{
                max_action.push(action);
            }
        }
    }else{
        let mut action_nb_vals: Vec<(Action, UBoard, LineInfo, f32, u128, (Option<Fail>, usize))> = Vec::new();

        for (action, idx) in LSBGenerator::from_uboard((att, def)){
            let next_line_info = line_info.next(idx);
            let hash_key = if is_black{
                (((att | action) as u128) << 64) | (def as u128)
            }else{
                ((def as u128) << 64) | ((att | action) as u128)
            };
            let hash_val = hashmap.get(&hash_key);
            
            match hash_val{
                Some(&(old_val, old_gen)) => {
                    action_nb_vals.push((
                        action,
                        (def, att | action),
                        next_line_info,
                        match old_val{
                            Ex(v) => - v,
                            Low(v) => - v,
                            High(v) => - (1.0 + v),
                        },
                        hash_key,
                        (Some(
                            match old_val{
                                Ex(v) => Ex(-v),
                                Low(v) => High(-v),
                                High(v) => Low(-v),
                            }
                        ), old_gen)
                    ))
                }
                None => {
                    let v = -e.evaluate(&(def, att), &next_line_info);
                    action_nb_vals.push((action, (def, att | action), next_line_info, v, hash_key, (None, 0)))
                }
            }
        }

        action_nb_vals.sort_by(|a, b| b.3.partial_cmp(&a.3).unwrap());

        for (move_idx, &(action, next_board, ref next_line_info, val, hash, (hit, old_depth))) in action_nb_vals.iter().enumerate(){
            let mut val=-2.0;
            let mut is_set = false;

            // hitありー＞Exのとき値を使う

            if let Some(fail_val) = hit.clone() 
                && old_depth >= depth - 1
            {
                match fail_val{
                    High(x) => {
                        if beta < x{
                            return (vec![action], High(x));
                        }
                    },
                    Low(x) => {
                        if alpha >= x{
                            continue;
                        }
                    },
                    Ex(x) => {
                        val = x;
                        is_set = true;
                    }
                }
            }
        }
    }

    let mut neg_def_one = [0; 7];
    for i in 0..7{
        neg_def_one[i] = !line_info.def.0[i];
    }
    return (vec![0], High(0.0));
}