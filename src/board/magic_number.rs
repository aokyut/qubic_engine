const HFLIP1: u64 = 0x5555_5555_5555_5555;
const HFLIP2: u64 = 0x3333_3333_3333_3333;
const XYZ1_MASK: u64 = 0x8000_0400_0020_0001;
const XYZ2_MASK: u64 = 0x1000_0200_0040_0008;
const XYZ3_MASK: u64 = 0x0001_0020_0400_8000;
const XYZ4_MASK: u64 = 0x0008_0040_0200_1000;

pub fn get_xyz_reach_mask(att: u64, def: u64, blank: u64) -> u64 {
    use super::pprint_u64;
    let d = ((def & HFLIP1) << 1) | ((def >> 1) & HFLIP1);
    let d = ((d & HFLIP2) << 2) | ((d >> 2) & HFLIP2);

    return blank
        & (XYZ1_ARRAY
            [((((att & XYZ1_MASK) | (d & XYZ2_MASK)).wrapping_mul(XYZ1)) >> 57) as usize]
            | XYZ2_ARRAY
                [((((att & XYZ2_MASK) | (d & XYZ1_MASK)).wrapping_mul(XYZ1)) >> 57) as usize]
            | XYZ3_ARRAY
                [((((att & XYZ3_MASK) | (d & XYZ4_MASK)).wrapping_mul(XYZ3)) >> 57) as usize]
            | XYZ4_ARRAY
                [((((att & XYZ4_MASK) | (d & XYZ3_MASK)).wrapping_mul(XYZ3)) >> 57) as usize]);
}
